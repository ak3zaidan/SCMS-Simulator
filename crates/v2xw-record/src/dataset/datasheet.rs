//! The datasheet generator — the port of `scms_sim_ref/datagen/datasheet.py`.
//!
//! *Datasheets for Datasets* (Gebru et al. 2021) is the format, and the legacy
//! `DATASHEET.md` is the section list. The per-run datasheet is the source of truth, as
//! the legacy root file says itself:
//!
//! > Every generated run also ships its own `datasets/<run>/DATASHEET.md` with the
//! > concrete, reproducible figures … for that exact seed + config — **that per-run file
//! > is the source of truth**.
//!
//! # What a datasheet must not do
//!
//! A datasheet is a provenance claim, so every number in it is computed from the tables
//! that were actually written and every claim it cannot support is written as *absent*
//! rather than as a plausible default. Three consequences, each of which the legacy
//! generator got right and each of which is easy to lose:
//!
//! * The **generator line** names this engine. A datasheet that claimed the legacy
//!   generator would be false provenance, and 08-measurement-and-data.md §6 asks for the
//!   difference to be stated here specifically.
//! * The **leakage lint result** is the linter's real verdict, pasted in. If the linter
//!   failed, the datasheet says FAIL — the exporter refuses to write the dataset at all in
//!   that case, so a FAIL line can only appear in a datasheet a caller generated by hand.
//! * A **build time** nobody supplied is `unknown`. This crate reads no clock.
//!
//! # Real bytes and modelled bytes
//!
//! One section is new and is the reason this generator was finished rather than left as a
//! port: *Byte provenance*. A byte count from a real encoder and a byte count from the
//! validated size model are the same kind of integer, land in the same column and mean
//! entirely different things — the first is a measurement of an encoding, the second is a
//! prediction of a model with its own stated tolerance. An envelope-overhead result is
//! citable in the first case and not in the second, and nothing in a table of integers
//! says which it is. [`super::bytes`] holds the join and the arithmetic; this file prints
//! it, and prints the consequence in a sentence rather than leaving the reader to infer it.
//!
//! # World-data licensing
//!
//! §9 requires the exporter to refuse a world bundle with no licence file and to write the
//! required attribution strings into `DATASHEET.md` and the manifest. The Distribution
//! section does that: simulation data under CC-BY-4.0 (ADR 0001), world geometry under
//! whatever its provenance demands, and the attribution strings reproduced verbatim.

use std::fmt::Write as _;

use super::assemble::MaDataset;
use super::bytes::ByteProvenanceReport;
use super::leakage::LeakageReport;
use super::manifest::{DatasetManifest, GENERATOR, ModelProvenance};
use super::tables::DatasetProfile;

/// Renders `DATASHEET.md` for one dataset.
///
/// The sections are the legacy ones, in the legacy order: Motivation, Collection /
/// generation, Composition, Label leakage prevention, Splits, Reproducibility,
/// Distribution / license. Three are added because this engine can support them and the
/// legacy one could not:
///
/// * **Model cards** — every card that produced a number, which 03-interfaces.md §12 makes
///   mandatory, now with each model's validation status, because a dataset is worth what
///   the models behind it are worth;
/// * **Byte provenance** — which byte counts came from a real encoder and which from a size
///   model, which is what decides whether an overhead result from the dataset can be cited;
/// * **Known defects of this profile** — the v1 defects this exporter reproduces on
///   purpose, named.
#[must_use]
pub fn render(dataset: &MaDataset, manifest: &DatasetManifest, lint: &LeakageReport) -> String {
    let mut s = String::with_capacity(8 * 1024);
    let profile = dataset.profile;

    let _ = writeln!(s, "# Datasheet — V2X misbehaviour-authority dataset");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "Following *Datasheets for Datasets* (Gebru et al.). This file describes **this run \
         only**: one seed, one scenario, the figures below computed from the tables beside it. \
         It is generated with the dataset and is the source of truth for it."
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "| | |");
    let _ = writeln!(s, "|---|---|");
    let _ = writeln!(
        s,
        "| Profile | `{}` (schema `ma_visible={}`, `ground_truth={}`) |",
        profile.as_str(),
        manifest.schema_versions["ma_visible"],
        manifest.schema_versions["ground_truth"]
    );
    let _ = writeln!(s, "| Seed | `{:#x}` ({}) |", manifest.seed, manifest.seed);
    let _ = writeln!(
        s,
        "| Scenario hash | `{}` |",
        or_unknown(&manifest.scenario_hash)
    );
    let _ = writeln!(s, "| World hash | `{}` |", or_unknown(&manifest.world_hash));
    let _ = writeln!(
        s,
        "| Recording content digest | `{}` |",
        or_unknown(&manifest.recording_content_digest)
    );
    let _ = writeln!(s, "| Data digest | `{}` |", manifest.data_digest_sha256);
    let _ = writeln!(s, "| Engine build | `{}` |", manifest.build_utc);
    let _ = writeln!(
        s,
        "| Simulated duration | {:.3} s |",
        dataset.run_duration_s
    );
    let _ = writeln!(s);

    // ---- Motivation ----------------------------------------------------------------
    let _ = writeln!(s, "## Motivation");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "**Purpose.** Train and evaluate centralized misbehaviour detection from the \
         perspective a real Misbehavior Authority has: misbehaviour *reports*, their \
         correlation, certificate and CRL status, and investigation and revocation \
         outcomes — not raw per-vehicle beacons. It complements per-vehicle corpora \
         (VeReMi, VeReMi NextGen) by modelling the credential lifecycle and the \
         authority's global decision problem. A VeReMi-compatible per-receiver export of \
         the same run is written by the `receiver-logs` profile, so the two views are \
         comparable on identical traffic."
    );
    let _ = writeln!(s);

    // ---- Collection / generation ----------------------------------------------------
    let _ = writeln!(s, "## Collection and generation");
    let _ = writeln!(s);
    let _ = writeln!(s, "**Generator.** `{GENERATOR}`");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "**Synthetic and deterministic.** Same seed and scenario reproduce this dataset. \
         Determinism comes from the engine's contract rather than from this exporter: all \
         randomness is drawn from RNG streams keyed by (domain, entity), the event loop is \
         single-threaded, no wall clock is read in engine-facing code, and no hash-map \
         iteration order reaches an output ordering or an id. Every exported float is \
         quantised at the writer to its field's declared grid (build decision D9), and a \
         scan reads the written files back and fails on any value off its grid."
    );
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "**Values differ from the legacy corpus, deliberately.** The v1 profile preserves \
         the legacy *schema* — file set, field names, sort orders, id formats, \
         vocabularies and canonical JSON bytes — so a consumer that pinned the schema keeps \
         working. It does not preserve the legacy *values*: this engine has a lane-level \
         world, a modeled radio channel and real verification queues where the reference \
         had a range-limited lossy channel and none. Build decision D9 retires the legacy \
         frozen digests for the same reason they were retired: they were unreproducible on \
         any non-Windows host. Cross-engine validation compares identifiers, enumerations, \
         counts, orderings and revocation sets exactly, and floats within 1e-9, never by \
         digest equality."
    );
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "**Standards profile.** Reports shaped to {}; certificates profiled to {}; linkage \
         values to {}.",
        manifest.standards_profile.report,
        manifest.standards_profile.cert,
        manifest.standards_profile.linkage
    );
    let _ = writeln!(s);

    // ---- Composition ---------------------------------------------------------------
    let _ = writeln!(s, "## Composition — tables actually written");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "Identifiers in MA-visible data appear **only** as opaque pseudonym-certificate \
         digests. True identities live exclusively in the ORACLE ground-truth tables, in a \
         separate directory, and are never joined into an MA-visible file."
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "### MA-visible (`ma/`) — may feed features");
    let _ = writeln!(s);
    let _ = writeln!(s, "| Table | Rows |");
    let _ = writeln!(s, "|---|---:|");
    let _ = writeln!(s, "| `ma_reports` | {} |", dataset.ma_reports.len());
    let _ = writeln!(s, "| `ma_cert_status` | {} |", dataset.ma_cert_status.len());
    let _ = writeln!(
        s,
        "| `ma_investigations` | {} |",
        dataset.ma_investigations.len()
    );
    let _ = writeln!(s, "| `ma_crl_events` | {} |", dataset.ma_crl_events.len());
    if profile.is_v2() {
        let _ = writeln!(
            s,
            "| `ma_crl_downloads` (v2) | {} |",
            dataset.ma_crl_downloads.len()
        );
        let _ = writeln!(
            s,
            "| `ma_report_transport` (v2) | {} |",
            dataset.ma_report_transport.len()
        );
    }
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "### Ground truth (`ground_truth/`) — labels and evaluation ONLY"
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "| Table | Rows |");
    let _ = writeln!(s, "|---|---:|");
    let _ = writeln!(s, "| `gt_vehicle` | {} |", dataset.gt_vehicle.len());
    let _ = writeln!(
        s,
        "| `gt_identity_map` | {} |",
        dataset.gt_identity_map.len()
    );
    let _ = writeln!(s, "| `gt_attacks` | {} |", dataset.gt_attacks.len());
    let _ = writeln!(
        s,
        "| `gt_report_labels` | {} |",
        dataset.gt_report_labels.len()
    );
    let _ = writeln!(
        s,
        "| `gt_linkage_revocation` | {} |",
        dataset.gt_linkage_revocation.len()
    );
    let _ = writeln!(
        s,
        "| `gt_emissions_sample` | {} |",
        dataset.gt_emissions_sample.len()
    );
    if profile.is_v2() {
        let _ = writeln!(
            s,
            "| `gt_kinematics_sample` (v2) | {} |",
            dataset.gt_kinematics_sample.len()
        );
        let _ = writeln!(
            s,
            "| `gt_revocation_stages` (v2) | {} |",
            dataset.gt_revocation_stages.len()
        );
    }
    let _ = writeln!(s);

    // ---- Composition figures --------------------------------------------------------
    let attackers = dataset.gt_vehicle.iter().filter(|v| v.is_attacker).count();
    let faulty = dataset.gt_vehicle.iter().filter(|v| v.is_faulty).count();
    let devices = dataset.gt_vehicle.len();
    let _ = writeln!(s, "### Fleet and label balance");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "- Devices: **{devices}** ({} infrastructure reporter{} excluded from the fleet tables)",
        dataset.rsu_count,
        if dataset.rsu_count == 1 { "" } else { "s" }
    );
    let _ = writeln!(
        s,
        "- Attackers: **{attackers}** ({}), faulty: **{faulty}** ({})",
        percent(attackers, devices),
        percent(faulty, devices)
    );
    let mut roles: std::collections::BTreeMap<&str, usize> = std::collections::BTreeMap::new();
    for v in dataset.gt_vehicle.iter().filter(|v| v.is_attacker) {
        *roles.entry(v.attacker_role.as_str()).or_default() += 1;
    }
    if roles.is_empty() {
        let _ = writeln!(s, "- Attacker roles: none in this run");
    } else {
        let _ = writeln!(
            s,
            "- Attacker roles: {}",
            roles
                .iter()
                .map(|(k, n)| format!("`{k}` × {n}"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    let mut correctness: std::collections::BTreeMap<&str, usize> =
        std::collections::BTreeMap::new();
    for l in &dataset.gt_report_labels {
        *correctness
            .entry(l.report_correctness.as_str())
            .or_default() += 1;
    }
    if correctness.is_empty() {
        let _ = writeln!(s, "- Report labels: no reports in this run");
    } else {
        let _ = writeln!(
            s,
            "- Report labels: {}",
            correctness
                .iter()
                .map(|(k, n)| format!("`{k}` × {n}"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    let _ = writeln!(s);

    // ---- Revocation outcome ---------------------------------------------------------
    let revoked = dataset.revoked_devices();
    let should: std::collections::BTreeSet<&str> = dataset
        .gt_linkage_revocation
        .iter()
        .filter(|r| r.should_have_been_revoked)
        .map(|r| r.true_vehicle_id.as_str())
        .collect();
    let revoked_refs: std::collections::BTreeSet<&str> =
        revoked.iter().map(String::as_str).collect();
    let tp = revoked_refs.intersection(&should).count();
    let _ = writeln!(s, "### Revocation outcome (per device, over the whole run)");
    let _ = writeln!(s);
    let _ = writeln!(s, "- Devices revoked: **{}**", revoked.len());
    let _ = writeln!(s, "- Devices that should have been: **{}**", should.len());
    let _ = writeln!(
        s,
        "- Precision: {} · Recall: {}",
        ratio(tp, revoked.len()),
        ratio(tp, should.len())
    );
    let _ = writeln!(
        s,
        "\nPrecision and recall here are *over devices*, which is the authority's actual \
         decision unit; a report-level figure is a different question and is computed by \
         the detection metrics rather than asserted here."
    );
    let _ = writeln!(s);

    // ---- Byte provenance ------------------------------------------------------------
    byte_provenance_section(&mut s, manifest.byte_provenance.as_ref());

    // ---- Leakage -------------------------------------------------------------------
    let _ = writeln!(s, "## Label leakage prevention");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "Features and labels are written to **separate files** and joined offline. A \
         build-breaking linter rejects any ground-truth field name — a real device id, a \
         true kinematic value, an attack or fault label, the exact fields F2MD leaked \
         (`senderRealId` / `reportedRealId`), or a `gt_`-prefixed column from the v2 \
         tables — appearing anywhere in a node-visible file, at any nesting depth. It also \
         refuses an `ORACLE`-tagged record in an MA file on its tag alone, and checks that \
         no true-identity *value* appears in an MA file under any column name."
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "**Result for this dataset:** {}", lint.summary());
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "The linter is tested by trying to smuggle a ground-truth column through every \
         profile — see `tests/leakage_smuggling.rs`. A check that cannot go red is not a \
         check."
    );
    let _ = writeln!(s);

    // ---- Splits --------------------------------------------------------------------
    let _ = writeln!(s, "## Splits");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "This exporter writes no split columns. Splits are assigned by the featurizer, \
         grouped by **true device** so no device's reports span splits, from a \
         deterministic hash of the device id (≈70/15/15 train/val/test), plus a \
         forward-in-time split for the deployment question. Grouping by device rather than \
         by report is the whole point: a per-report split leaks, because two reports about \
         one device are not independent."
    );
    let _ = writeln!(s);

    // ---- Model cards ---------------------------------------------------------------
    model_card_section(&mut s, manifest);

    // ---- Known defects -------------------------------------------------------------
    let _ = writeln!(s, "## Known defects of this profile");
    let _ = writeln!(s);
    match profile {
        DatasetProfile::V1 => {
            let _ = writeln!(
                s,
                "The v1 profile reproduces the legacy schema **including its defects**, \
                 because a consumer that pinned the schema depends on them. Each one is \
                 listed so nobody mistakes it for a measurement:"
            );
            let _ = writeln!(s);
            let _ = writeln!(
                s,
                "- `ma_cert_status.valid_from` is `0.0` and `valid_to` is the run duration for every certificate, whatever its real validity window."
            );
            let _ = writeln!(
                s,
                "- `ma_reports.cert_validity` is all-true for every report, so it carries no information."
            );
            let _ = writeln!(
                s,
                "- `ma_reports.cert_crl_status` is the literal `\"active\"` for every report."
            );
            let _ = writeln!(
                s,
                "- `ma_investigations` has a row only where the authority revoked, so dismissed cases leave no trace and `revocation_decision` is always `revoke`."
            );
            let _ = writeln!(s);
            let _ = writeln!(
                s,
                "The v2 profile fixes all four additively: real validity windows, a real `crl_status` including `unknown`, `verification_status` / `verify_latency_ms` / `rx_rssi_dbm` / `rat` on each report, and every case including the dismissed ones."
            );
        }
        DatasetProfile::V2 => {
            let _ = writeln!(
                s,
                "The v2 profile is additive over v1: every v1 column is present with v1 \
                 semantics *except* the four v1 defects, which now carry real values — \
                 `valid_from` / `valid_to` are the certificate's real window, `crl_status` \
                 can be `unknown`, and `ma_investigations` includes dismissed cases. A \
                 consumer that needs the frozen v1 semantics asks for the v1 profile or \
                 runs `dataset migrate --to v1`."
            );
        }
    }
    let _ = writeln!(s);

    // ---- Reproducibility -----------------------------------------------------------
    let _ = writeln!(s, "## Reproducibility");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "`manifest.json` carries the seed, the full scenario configuration, the generator \
         and schema versions, the standards profile, each file's SHA-256 and the aggregate \
         data digest. Because the run is deterministic, this dataset can be *reproduced* \
         from its manifest rather than redistributed."
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "- Files digested: **{}**", manifest.outputs.len());
    let _ = writeln!(
        s,
        "- Aggregate data digest: `{}`",
        manifest.data_digest_sha256
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "| File | SHA-256 |");
    let _ = writeln!(s, "|---|---|");
    for f in &manifest.outputs {
        let _ = writeln!(s, "| `{}` | `{}` |", f.path, short(&f.sha256));
    }
    let _ = writeln!(s);

    // ---- Distribution --------------------------------------------------------------
    let _ = writeln!(s, "## Distribution and licence");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "**Simulation data** — messages, telemetry, traces and the MA tables — is \
         CC-BY-4.0 (ADR 0001). **World geometry** is not included in this bundle; \
         simulation data references the world by content hash (`{}`) and carries \
         coordinates, not a copy of the road graph.",
        or_unknown(&manifest.world_hash)
    );
    let _ = writeln!(s);
    match &manifest.world_licence {
        Some(licence) => {
            let _ = writeln!(
                s,
                "The world this run drove on is derived from licensed data and its bundle \
                 is **{licence}**. Required attribution:"
            );
            let _ = writeln!(s);
            if manifest.world_attribution.is_empty() {
                let _ = writeln!(
                    s,
                    "- *none supplied* — which is a defect: §9 requires the exporter to \
                     refuse a world bundle without its attribution strings."
                );
            } else {
                for a in &manifest.world_attribution {
                    let _ = writeln!(s, "- {a}");
                }
            }
        }
        None => {
            let _ = writeln!(
                s,
                "No world licence was supplied, so no world bundle may be published \
                 alongside this dataset. A world derived from OSM or Overture data is \
                 very likely a Derivative Database and stays under ODbL with share-alike \
                 and attribution (08-measurement-and-data.md §9); the exporter refuses to \
                 write a world bundle without its licence file."
            );
        }
    }
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "Whether coordinate-only simulation data derived by driving on an OSM network is \
         itself a derivative database is an open legal question (11-open-questions.md); \
         the conservative default is to publish world bundles under ODbL and simulation \
         data under CC-BY-4.0 with the world bundle attached."
    );

    s
}

/// The Byte provenance section: which of this dataset's byte counts came from real bytes.
///
/// `None` means the writer was handed no tally at all, which is a different statement from
/// "nothing was transmitted" and is written as such. A datasheet that printed "no byte
/// counts" for a dataset whose exporter simply was not given the tally would be making a
/// claim about the run out of a gap in its own inputs.
fn byte_provenance_section(s: &mut String, report: Option<&ByteProvenanceReport>) {
    let _ = writeln!(s, "## Byte provenance — real bytes and modelled bytes");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "A byte count from a real ASN.1 encoder and a byte count from the validated size \
         model of 04-models.md §8.4 are the same kind of integer and mean different things. \
         The first is the length of octets that a decoder can read back, so an \
         envelope-overhead figure computed from it is a measurement of an encoding. The \
         second is a *prediction* whose own tolerance is stated on the size model's card, \
         and the payload bytes behind it are `0xA5` placeholders. **This distinction \
         decides whether an overhead result from this dataset can be cited as a \
         measurement**, and nothing in a table of integers reveals it, which is why it is \
         stated here."
    );
    let _ = writeln!(s);
    let Some(report) = report else {
        let _ = writeln!(
            s,
            "*Not stated.* This dataset was written without a transmission tally, so this \
             datasheet cannot say what produced its byte counts. That is a gap in the \
             exporter's inputs and **not** a statement that nothing was transmitted: treat \
             every byte count in this dataset as being of unknown provenance, and do not \
             cite an overhead figure from it."
        );
        let _ = writeln!(s);
        return;
    };
    let _ = writeln!(s, "**Verdict.** {}", report.verdict());
    let _ = writeln!(s);
    if report.is_empty() {
        return;
    }
    let _ = writeln!(
        s,
        "| Message type | Bytes came from | Messages | Bytes on wire | Payload bytes | Envelope bytes |"
    );
    let _ = writeln!(s, "|---|---|---:|---:|---:|---:|");
    for row in &report.rows {
        let _ = writeln!(
            s,
            "| `{}` | {} | {} | {} | {} | {} |",
            row.msg_type,
            row.provenance.label(),
            row.bytes.messages,
            row.bytes.bytes_on_wire,
            partial_sum(
                row.bytes.payload_bytes,
                row.bytes.payload_stated,
                row.bytes.messages
            ),
            partial_sum(
                row.bytes.envelope_bytes,
                row.bytes.envelope_stated,
                row.bytes.messages
            ),
        );
    }
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "- Real wire bytes: **{}** · size-model bytes: **{}** · undeclared: **{}** (of {} \
         total)",
        report.real_bytes, report.modelled_bytes, report.undeclared_bytes, report.bytes_on_wire
    );
    if report.undeclared_bytes > 0 {
        let _ = writeln!(
            s,
            "- An **undeclared** message type is one the engine sent and did not say which \
             codec produced. Its bytes are counted as neither real nor modelled, so a \
             missing declaration can never make a byte count look citable; it is a defect \
             in the run's provenance and should be reported."
        );
    }
    if !report.declared_types_unused.is_empty() {
        let _ = writeln!(
            s,
            "- Declared but unused in this run: {}. Not an error — a scenario need not send \
             every message type the engine can encode — and listed so a declaration that \
             describes a different run is visible.",
            report
                .declared_types_unused
                .iter()
                .map(|t| format!("`{t}`"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    let _ = writeln!(s);
}

/// A sum over a subset of the rows, spelled so it cannot be read as a sum over all of
/// them.
///
/// A payload total covering a third of the messages would otherwise read as a small
/// payload rather than as a partly-absent field — the same failure the metrics crate
/// refuses by reporting insufficiency instead of a point estimate.
fn partial_sum(total: u64, stated: u64, messages: u64) -> String {
    if stated == 0 {
        "not stated".to_string()
    } else if stated == messages {
        total.to_string()
    } else {
        format!("{total} (over {stated} of {messages})")
    }
}

/// The Model cards section: every card that produced a number, with its validation status.
///
/// The validation status is the point. A dataset is worth what the models behind it are
/// worth, and `literature-checked` and `unvalidated` are different objects; a consumer who
/// has to open the documentation site to find out which is which will not do it.
fn model_card_section(s: &mut String, manifest: &DatasetManifest) {
    let _ = writeln!(s, "## Model cards behind these numbers");
    let _ = writeln!(s);
    if !manifest.models.is_empty() {
        let checked = manifest
            .models
            .iter()
            .filter(|m| m.externally_checked())
            .count();
        let uncalibrated: u32 = manifest
            .models
            .iter()
            .map(|m| m.todo_calibrate)
            .fold(0u32, u32::saturating_add);
        let _ = writeln!(
            s,
            "{} model card(s) produced numbers in this dataset. Compared against something \
             outside the engine — `literature-checked` or `field-checked` — **{} of {}**. \
             The rest were checked against their own authors' expectations, which is a \
             weaker claim and is stated here rather than left to be discovered. Between \
             them the cards carry **{} parameter default(s) still marked \
             `todo-calibrate`**: values an implementer chose, each with a plan for \
             replacing it and none supported by a source.",
            manifest.models.len(),
            checked,
            manifest.models.len(),
            uncalibrated
        );
        let _ = writeln!(s);
        let _ = writeln!(
            s,
            "| Model | Version | Validation | Tiers | Uncalibrated defaults | Card hash |"
        );
        let _ = writeln!(s, "|---|---|---|---|---:|---|");
        for m in &manifest.models {
            let _ = writeln!(
                s,
                "| `{}` | `{}` | {} | {} | {} | `{}` |",
                m.id,
                m.version,
                validation_label(m),
                if m.tiers.is_empty() {
                    "none declared".to_string()
                } else {
                    m.tiers.join(", ")
                },
                m.todo_calibrate,
                short(&m.content_hash)
            );
        }
        let _ = writeln!(s);
        let _ = writeln!(
            s,
            "A validation status says what *kind* of check was done, not how hard it was. \
             The generated documentation site's validation-campaign page joins these \
             statuses against the validation suite's own outcomes and against the defect \
             registers, and reports where they disagree."
        );
        let _ = writeln!(s);
        return;
    }
    if manifest.model_cards.is_empty() {
        let _ = writeln!(
            s,
            "*None recorded.* The engine did not hand this exporter a card list, so none \
             is claimed. A publishable dataset should carry one: 03-interfaces.md §12 \
             makes a card mandatory for every plug-in, and every default on a card cites a \
             source or is marked `todo-calibrate` with a plan."
        );
        let _ = writeln!(s);
        return;
    }
    let _ = writeln!(
        s,
        "The engine supplied names and versions only, so this section cannot say how far \
         any of these models was validated or how many of their defaults are still \
         uncalibrated. A publishable dataset should carry the fuller list."
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "| Model | Version |");
    let _ = writeln!(s, "|---|---|");
    for card in &manifest.model_cards {
        let _ = writeln!(
            s,
            "| `{}` | `{}` |",
            card.get("id").map_or("?", String::as_str),
            card.get("version").map_or("?", String::as_str)
        );
    }
    let _ = writeln!(s);
}

/// One model's validation status, spelled as the card schema spells it plus what it means.
fn validation_label(m: &ModelProvenance) -> &'static str {
    use v2xw_core::card::ValidationStatus as V;
    match m.validation_status {
        V::Unvalidated => "`unvalidated` — nothing checked",
        V::UnitTested => "`unit-tested` — checked against itself only",
        V::LiteratureChecked => "`literature-checked` — against published figures",
        V::FieldChecked => "`field-checked` — against measurements",
    }
}

fn or_unknown(s: &str) -> &str {
    if s.is_empty() { "unknown" } else { s }
}

fn short(hex: &str) -> &str {
    if hex.len() > 16 { &hex[..16] } else { hex }
}

/// A count as a percentage of a total, or `n/a` for an empty total.
///
/// Not `0 %`: zero of zero is not zero percent, and a datasheet that says `0 %` where it
/// means "there was nothing to divide by" is making a claim it cannot support.
fn percent(n: usize, total: usize) -> String {
    if total == 0 {
        "n/a".to_string()
    } else {
        format!("{:.1} %", 100.0 * n as f64 / total as f64)
    }
}

fn ratio(n: usize, total: usize) -> String {
    if total == 0 {
        "n/a (no cases)".to_string()
    } else {
        format!("{:.3}", n as f64 / total as f64)
    }
}

